"""Verify blind packet identity, missing-label rejection and non-destructive review artifact handling."""

import copy
import json
import logging
from pathlib import Path

import pytest

from scripts import retrieval_relevance_review as review

CORPUS = Path(__file__).parent / "fixtures/retrieval/d27-review-challenge.json"


@pytest.fixture
def corpus():
    """Load the unlabeled challenge without model results or generated relevance judgments."""
    return review.read_json(CORPUS)


@pytest.fixture
def response(corpus):
    """Create synthetic protocol labels for tests only, never retained as human judgments."""
    packet = review.build_packet(corpus)
    result = review.review_template(packet)
    result.update(
        reviewer="TEST FIXTURE ONLY",
        reviewed_at="2026-10-19T12:00:00+07:00",
        attestation="I independently reviewed every query and document without viewing model rankings or scores.",
    )
    for query in result["queries"]:
        for row in query["documents"]:
            row.update(
                relevant=False,
                reason="Synthetic protocol fixture, not a human judgment.",
            )
    return result


def test_packet_blind_complete_stable(corpus):
    """Cover every pair in model-independent order and omit old labels, role names and scores."""
    packet = review.build_packet(corpus)
    assert packet == review.build_packet(copy.deepcopy(corpus))
    assert sum(len(q["documents"]) for q in packet["queries"]) == 64
    for query in packet["queries"]:
        assert {row["id"] for row in query["documents"]} == {
            row["id"] for row in corpus["documents"]
        }
        assert all(
            row["relevant"] is None
            and row["reason"] == ""
            and set(row) == {"id", "text", "relevant", "reason"}
            for row in query["documents"]
        )


def test_pending_template_is_not_review(corpus):
    """Refuse to turn a generated pending packet into accepted human evidence."""
    packet = review.build_packet(corpus)
    with pytest.raises(ValueError, match="review_metadata_missing"):
        review.validate_review(corpus, packet, review.review_template(packet))


def test_absent_answers_and_no_adoption_claim(corpus, response):
    """Allow all-negative relevance without manufacturing a relevant target or adoption approval."""
    result = review.validate_review(corpus, review.build_packet(corpus), response)
    assert result["absent_answer_queries"] == 8
    assert all(row["relevant"] == [] for row in result["queries"])
    assert result["status"] == "STRUCTURALLY_VALIDATED_ONLY"
    assert result["benchmark_executed"] is False
    assert result["adoption_approved"] is False


@pytest.mark.parametrize(
    "change,error",
    [
        ("packet", "review_packet_changed"),
        ("attestation", "review_attestation_missing"),
        ("timestamp", "review_timestamp_invalid"),
        ("naive_time", "review_timestamp_invalid"),
        ("missing_query", "review_queries_incomplete"),
        ("duplicate_query", "review_query_identity_invalid"),
        ("missing_pair", "review_pairs_incomplete"),
        ("duplicate_pair", "review_pair_identity_invalid"),
        ("foreign_pair", "review_pair_identity_invalid"),
        ("missing_label", "review_labels_pending_or_invalid"),
        ("numeric_label", "review_labels_pending_or_invalid"),
        ("reason", "review_labels_pending_or_invalid"),
        ("extra_field", "review_shape_invalid"),
    ],
)
def test_review_corruption_rejected(corpus, response, change, error):
    """Reject partial, mismatched or machine-coerced judgments before any evaluation."""
    first = response["queries"][0]["documents"][0]
    if change == "packet":
        response["packet_sha256"] = "0" * 64
    elif change == "attestation":
        response["attestation"] = "generated by an agent"
    elif change == "timestamp":
        response["reviewed_at"] = "yesterday"
    elif change == "naive_time":
        response["reviewed_at"] = "2026-10-19T12:00:00"
    elif change == "missing_query":
        response["queries"].pop()
    elif change == "duplicate_query":
        response["queries"][1] = copy.deepcopy(response["queries"][0])
    elif change == "missing_pair":
        response["queries"][0]["documents"].pop()
    elif change == "duplicate_pair":
        response["queries"][0]["documents"][1] = copy.deepcopy(first)
    elif change == "foreign_pair":
        first["id"] = "unknown"
    elif change == "missing_label":
        first["relevant"] = None
    elif change == "numeric_label":
        first["relevant"] = 0
    elif change == "reason":
        first["reason"] = " "
    else:
        response["extra"] = True
    with pytest.raises(ValueError, match=error):
        review.validate_review(corpus, review.build_packet(corpus), response)


@pytest.mark.parametrize(
    "change", ["labels", "duplicate", "empty", "extra", "oversized"]
)
def test_unlabeled_corpus_contract(corpus, change):
    """Reject prefilled labels, hidden evaluation fields and malformed challenge identity."""
    if change == "labels":
        corpus["queries"][0]["relevant"] = ["doc-a"]
    elif change == "duplicate":
        corpus["documents"][1]["id"] = corpus["documents"][0]["id"]
    elif change == "empty":
        corpus["queries"] = []
    elif change == "extra":
        corpus["scores"] = [1]
    else:
        corpus["documents"][0]["text"] = "x" * 16385
    with pytest.raises(ValueError):
        review.build_packet(corpus)


