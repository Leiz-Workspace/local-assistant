@pytest.mark.parametrize("raw", ['{"x":1,"x":2}', '{"x":NaN}', '{"x":Infinity}'])
def test_json_ambiguity_rejected(tmp_path, raw):
    """Reject duplicate keys and nonfinite numeric extensions before interpreting evidence."""
    path = tmp_path / "input.json"
    path.write_text(raw)
    with pytest.raises(ValueError):
        review.read_json(path)


def test_oversized_input_rejected(tmp_path):
    """Bound input reads before JSON parsing."""
    path = tmp_path / "input.json"
    path.write_bytes(b" " * (review.MAX_BYTES + 1))
    with pytest.raises(ValueError, match="json_size_invalid"):
        review.read_json(path)


def test_exclusive_write_and_safe_audit(tmp_path, caplog):
    """Preserve old evidence, private output permissions and text-free audit logs."""
    path = tmp_path / "artifact.json"
    with caplog.at_level(logging.INFO):
        review.write_new(path, {"private": "do-not-log-this"})
    assert path.stat().st_mode & 0o777 == 0o600
    assert "relevance_artifact_created" in caplog.text
    assert "do-not-log-this" not in caplog.text
    with pytest.raises(FileExistsError):
        review.write_new(path, {})
    assert json.loads(path.read_text()) == {"private": "do-not-log-this"}


def test_cli_packet_pending_and_validate(tmp_path, corpus, response):
    """Exercise packet creation, safe refusal, unchanged output and explicit structural acceptance."""
    packet_path, response_path, output = (
        tmp_path / name for name in ("packet.json", "review.json", "accepted.json")
    )
    common = [
        "--corpus",
        str(CORPUS),
        "--packet",
        str(packet_path),
        "--review",
        str(response_path),
    ]
    assert review.main(["packet", *common]) == 0
    original = response_path.read_bytes()
    assert review.main(["packet", *common]) == 1
    assert response_path.read_bytes() == original
    assert review.main(["validate", *common, "--output", str(output)]) == 1
    assert not output.exists()
    response_path.write_text(json.dumps(response))
    assert review.main(["validate", *common, "--output", str(output)]) == 0
    assert review.main(["validate", *common, "--output", str(output)]) == 1


def test_symlink_destination_not_followed(tmp_path):
    """Refuse a pre-existing output symlink instead of modifying its target."""
    target, link = tmp_path / "target", tmp_path / "link"
    target.write_text("unchanged")
    link.symlink_to(target)
    with pytest.raises(FileExistsError):
        review.write_new(link, {})
    assert target.read_text() == "unchanged"
