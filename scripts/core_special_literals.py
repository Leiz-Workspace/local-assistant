"""Derive the CORE special-token literal list from the GGUF vocabularies and check or rewrite the pinned module (ADR-195)."""

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "configs/models.yaml"
MODULE = ROOT / "src/application/services/special_literals.py"
ROLES = ("core", "unrestricted")
BEGIN = "# BEGIN GENERATED by scripts/core_special_literals.py --write; do not edit by hand.\n"
END = "# END GENERATED\n"

# GGUF value types (gguf.h).
SCALARS = {
    0: "<B",
    1: "<b",
    2: "<H",
    3: "<h",
    4: "<I",
    5: "<i",
    6: "<f",
    7: "<?",
    10: "<Q",
    11: "<q",
    12: "<d",
}
STRING, ARRAY = 8, 9
WANTED = {"tokenizer.ggml.tokens", "tokenizer.ggml.token_type"}

# llama_token_type values and the cached kinds (llama-vocab.cpp: the special
# tokens cache keeps CONTROL, USER_DEFINED and UNKNOWN attributes).
TYPE_KIND = {2: "unknown", 3: "control", 4: "user_defined"}

# Token texts that the pinned llama.cpp (configs/llama-cpp-commit.txt) promotes
# to CONTROL by name (llama-vocab.cpp: EOT, EOM, FIM and EOG detection). The
# list is a conservative superset: it ignores the "first match wins" order and
# the later demotions, so a token here is always treated as special.
CONTROL_NAMES = frozenset(
    {
        "<|eot_id|>",
        "<|im_end|>",
        "<|end|>",
        "<end_of_turn>",
        "<|endoftext|>",
        "<|end_of_text|>",
        "<EOT>",
        "_<EOT>",
        "[EOT]",
        "<｜end▁of▁sentence｜>",
        "<end_of_utterance>",
        "<|eom_id|>",
        "<|fim_prefix|>",
        "<fim-prefix>",
        "<fim_prefix>",
        "<｜fim▁begin｜>",
        "<PRE>",
        "▁<PRE>",
        "<|code_prefix|>",
        "<|prefix|>",
        "<|plamo:fim_prefix|>",
        "<|fim_suffix|>",
        "<fim-suffix>",
        "<fim_suffix>",
        "<｜fim▁hole｜>",
        "<SUF>",
        "▁<SUF>",
        "<|code_suffix|>",
        "<|suffix|>",
        "<|plamo:fim_suffix|>",
        "<|fim_middle|>",
        "<fim-middle>",
        "<fim_middle>",
        "<｜fim▁end｜>",
        "<MID>",
        "▁<MID>",
        "<|code_middle|>",
        "<|middle|>",
        "<|plamo:fim_middle|>",
        "<|fim_pad|>",
        "<fim-pad>",
        "<fim_pad>",
        "<PAD>",
        "[PAD]",
        "<|fim_repo|>",
        "<|repo_name|>",
        "<fim-repo>",
        "<REPO>",
        "<reponame>",
        "<|file_sep|>",
        "<|plamo:file_separator|>",
        "<|return|>",
        "<|call|>",
        "<|flush|>",
        "<|calls|>",
        "</s>",
        "[EOS]",
        "<eos>",
        "<turn|>",
        "<|tool_response>",
        "[e~[",
        "<|ifm|im_end|>",
    }
)
# Token texts that the pinned llama.cpp forces to USER_DEFINED (gpt-oss).
USER_DEFINED_NAMES = frozenset(
    {"<|channel|>", "<|message|>", "<|start|>", "<|constrain|>"}
)


class LiteralError(Exception):
    """Report a closed reason code for a vocabulary, configuration or module problem."""


def _read(file, fmt):
    """Read one little-endian scalar."""
    size = struct.calcsize(fmt)
    data = file.read(size)
    if len(data) != size:
        raise LiteralError("gguf_truncated")
    return struct.unpack(fmt, data)[0]


def _string(file):
    """Read one GGUF string."""
    size = _read(file, "<Q")
    data = file.read(size)
    if len(data) != size:
        raise LiteralError("gguf_truncated")
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise LiteralError("gguf_string_not_utf8") from exc


def _value(file, kind, keep):
    """Read or skip one GGUF value of the given type."""
    if kind == STRING:
        return _string(file)
    if kind == ARRAY:
        item, count = _read(file, "<I"), _read(file, "<Q")
        if not keep and item in SCALARS:
            file.seek(struct.calcsize(SCALARS[item]) * count, 1)
            return None
        values = [_value(file, item, keep) for _ in range(count)]
        return values if keep else None
    if kind not in SCALARS:
        raise LiteralError("gguf_unknown_type")
    return _read(file, SCALARS[kind])


def read_vocab(path):
    """Return the token texts and token types from a GGUF v2 or v3 file using only the standard library."""
    with open(path, "rb") as file:
        if file.read(4) != b"GGUF":
            raise LiteralError("gguf_magic")
        if _read(file, "<I") not in (2, 3):
            raise LiteralError("gguf_version")
        _read(file, "<Q")
        found = {}
        for _ in range(_read(file, "<Q")):
            key = _string(file)
            kind = _read(file, "<I")
            value = _value(file, kind, key in WANTED)
            if key in WANTED:
                found[key] = value
    tokens = found.get("tokenizer.ggml.tokens")
    types = found.get("tokenizer.ggml.token_type")
    if (
        not isinstance(tokens, list)
        or not isinstance(types, list)
        or len(tokens) != len(types)
    ):
        raise LiteralError("gguf_vocab_missing")
    return tokens, types


def special_tokens(tokens, types):
    """Apply the pinned llama.cpp attribute rules and return (id, kind, text) for every cached special token."""
    result = []
    for token_id, (text, token_type) in enumerate(zip(tokens, types)):
        kind = TYPE_KIND.get(token_type)
        if text in USER_DEFINED_NAMES:
            kind = "user_defined"
        elif kind is None and text in CONTROL_NAMES:
            kind = "control"
        if kind is not None:
            result.append((token_id, kind, text))
    for _, _, text in result:
        if (
            len(text) < 2
            or not text.startswith("<")
            or text.count("<") != 1
            or chr(92) in text
        ):
            raise LiteralError("literal_shape")
    if not result:
        raise LiteralError("no_special_tokens")
    return result


def sha256_file(path):
    """Hash a file in 8 MiB blocks."""
    digest = hashlib.sha256()
    with open(path, "rb") as file:
        for block in iter(lambda: file.read(8 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def configured_models(config):
    """Return the configured path and sha256 for each bound role."""
    with open(config, encoding="utf-8") as file:
        models = yaml.safe_load(file)["models"]
    result = {}
    for role in ROLES:
        path, digest = models[role].get("path"), models[role].get("sha256")
        if (
            not isinstance(path, str)
            or not isinstance(digest, str)
            or len(digest) != 64
        ):
            raise LiteralError("config_model_invalid")
        result[role] = (path, digest.lower())
    return result


def render(tokens, digests):
    """Render the generated block of the pinned module."""
    lines = [BEGIN, "CORE_SPECIAL_TOKENS = (\n"]
    lines += [
        f"    ({token_id}, {json.dumps(kind)}, {json.dumps(text, ensure_ascii=False)}),\n"
        for token_id, kind, text in tokens
    ]
    lines += [")\n", "BOUND_MODEL_SHA256 = {\n"]
    lines += [f'    "{role}": "{digests[role]}",\n' for role in ROLES]
    lines += ["}\n", END]
    return "".join(lines)


def splice(module_text, block):
    """Replace the generated block inside the module text."""
    start, end = module_text.find(BEGIN), module_text.find(END)
    if (
        start < 0
        or end < start
        or module_text.count(BEGIN) != 1
        or module_text.count(END) != 1
    ):
        raise LiteralError("module_markers")
    return module_text[:start] + block + module_text[end + len(END) :]


def derive(config, root, verify_hash):
    """Read both bound GGUF files, require identical special lists and return the rendered block."""
    models = configured_models(config)
    lists = {}
    for role, (path, digest) in models.items():
        gguf = (root / path) if not Path(path).is_absolute() else Path(path)
        if not gguf.is_file():
            raise LiteralError(f"gguf_missing_{role}")
        if verify_hash and sha256_file(gguf) != digest:
            raise LiteralError(f"gguf_sha256_mismatch_{role}")
        lists[role] = special_tokens(*read_vocab(gguf))
    if lists["core"] != lists["unrestricted"]:
        raise LiteralError("special_lists_differ")
    return render(
        lists["core"], {role: digest for role, (_, digest) in models.items()}
    ), len(lists["core"])


def main(argv=None):
    """Check or rewrite the pinned special-literal list."""
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when the module differs from the GGUF files",
    )
    mode.add_argument(
        "--write", action="store_true", help="rewrite the generated block of the module"
    )
    parser.add_argument("--config", type=Path, default=CONFIG)
    parser.add_argument("--module", type=Path, default=MODULE)
    parser.add_argument(
        "--root", type=Path, default=ROOT, help="base for relative model paths"
    )
    parser.add_argument(
        "--skip-hash",
        action="store_true",
        help="do not hash the GGUF files against the config",
    )
    args = parser.parse_args(argv)
    try:
        block, count = derive(args.config, args.root, not args.skip_hash)
        current = args.module.read_text(encoding="utf-8")
        updated = splice(current, block)
    except (LiteralError, OSError, KeyError, TypeError, yaml.YAMLError) as exc:
        reason = exc.args[0] if isinstance(exc, LiteralError) else type(exc).__name__
        print(f"special_literals_error reason={reason}", file=sys.stderr)
        return 2
    if args.check:
        state = "current" if updated == current else "stale"
        print(f"special_literals_{state} count={count} hashed={not args.skip_hash}")
        return 0 if updated == current else 1
    if updated != current:
        args.module.write_text(updated, encoding="utf-8")
    print(f"special_literals_written count={count} changed={updated != current}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
