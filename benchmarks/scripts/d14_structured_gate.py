def obj(fields):
    """Declare structural object fields without supplying expected answers, constants, enum choices or source-derived value restrictions."""
    return dict(
        type="object",
        properties=fields,
        required=list(fields),
        additionalProperties=False,
    )


def arr(item):
    """Declare a generic bounded array whose free values are generated by the model."""
    return dict(type="array", items=item, maxItems=64)


def string():
    """Declare a bounded free string without a target value or label restriction."""
    return dict(type="string", maxLength=4096)


