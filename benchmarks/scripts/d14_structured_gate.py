async def measure(client, profile, case, root):
    """Send only the actual question/source/image and structural schema, retain one first native response and score exact values without repair."""
    directory = root / case["id"]
    directory.mkdir(mode=0o700)
    adapter = StructuredProfileAdapter(
        profile=profile,
        schema=case["schema"],
        endpoint="http://127.0.0.1:18080",
        max_tokens=256,
        timeout=90 if case["category"] == "memory_context" else 60,
    )
    row = dict(
        id=case["id"],
        category=case["category"],
        model_requests=0,
        format_passed=False,
        functional_passed=False,
    )
    try:
        calibration = None
        if case["category"] == "memory_context":
            prompt, calibration = await BASE["context_prompt"](client, case)
        else:
            prompt = case["prompt"]
        images = ((ROOT / case["image"]).read_bytes(),) if "image" in case else ()
        row["model_requests"] = 1
        result = await adapter.complete(
            prompt, images=images, stream=case.get("stream", False)
        )
        valid_context = (
            case["category"] != "memory_context"
            or 30000 <= result.input_tokens <= 32000
        )
        row.update(
            format_passed=True,
            functional_passed=bool(
                valid_context and BASE["strict_score"](result.content, case["expected"])
            ),
            result=asdict(result),
            calibration=calibration,
        )
    except Exception as exc:
        row.update(
            error_type=type(exc).__name__,
            error_code=getattr(exc, "code", "gate_first_failure"),
        )
    finally:
        row["model_requests"] = int(adapter.generation_dispatched)
        if adapter.last_request is not None:
            publish(directory / "native-request.json", adapter.last_request)
        publish(directory / "native-response.bin", adapter.last_response)
        publish(directory / "measurement.json", row)
        logger.info(
            "structured_gate_first_case profile=%s id=%s format=%s functional=%s",
            profile,
            case["id"],
            row["format_passed"],
            row["functional_passed"],
        )
    return row


def validate_unmeasured_suffix(prior):
    """Require complete first CORE accounting and a never-loaded UNRESTRICTED suffix; preserve all quality failures without repeating a case."""
    core = prior.get("profiles", {}).get("core", {})
    other = prior.get("profiles", {}).get("unrestricted", {})
    if (
        prior.get("status") != "INCOMPLETE"
        or prior.get("runtime_baseline_restored") is not True
        or len(core.get("rows", [])) != 42
        or len({r["id"] for r in core["rows"]}) != 42
        or any(r.get("model_requests") != 1 for r in core["rows"])
        or core.get("runtime", {}).get("exit_code") != 0
        or core["runtime"].get("reaped") is not True
        or core.get("cancellation", {}).get("native_slot_retired") is not True
        or other.get("rows") != []
        or other.get("runtime", {}).get("pid") is not None
    ):
        raise ValueError("structured_suffix_already_attempted_or_incomplete")
    logger.info("structured_unmeasured_suffix_verified")
    return core


async def run():
    """Run one frozen fresh42-case/profile gate with all first failures retained and owned native processes retired before final assessment."""
    frozen = json.loads(FREEZE.read_text())
    for path, expected in frozen["sha256"].items():
        if BASE["digest"](ROOT / path) != expected:
            raise ValueError("structured_frozen_input_changed")
    application = source_manifest()
    if application != frozen["application_sha256"]:
        raise ValueError("structured_application_changed")
    before = BASE["local_state"]()
    if before["native_pids"]:
        raise ValueError("structured_native_busy")
    summary = dict(
        description="Fresh schema-constrained D14 quality gate with free answer values; original D14 first outcomes remain unchanged.",
        status="INCOMPLETE",
        profiles={},
        baseline=before,
        automatic_retries=0,
        old_cases_regenerated=0,
        answers_in_schema=False,
    )
    publish(OUTPUT / "execution-freeze.json", frozen)
    if "retained_prior_result" in frozen:
        prior_path = ROOT / frozen["retained_prior_result"]["path"]
        if BASE["digest"](prior_path) != frozen["retained_prior_result"]["sha256"]:
            raise ValueError("structured_prior_result_changed")
        if {p.name for p in (prior_path.parent / "unrestricted").iterdir()} - {
            "preflight.json"
        }:
            raise ValueError("structured_prior_suffix_has_native_artifacts")
        summary["profiles"]["core"] = validate_unmeasured_suffix(
            json.loads(prior_path.read_text())
        )
        summary["retained_prior_result"] = frozen["retained_prior_result"]
        summary["profile_artifact_roots"] = dict(
            core=str(prior_path.parent / "core"),
            unrestricted=str(OUTPUT / "unrestricted"),
        )
    try:
        async with asyncio.timeout(2400):
            for profile in frozen.get("profiles_to_execute", ["core", "unrestricted"]):
                root = OUTPUT / profile
                root.mkdir(mode=0o700)
                server = BASE["OwnedServer"](profile, root)
                rows = []
                summary["profiles"][profile] = dict(rows=rows)
                try:
                    await server.start()
                    async with httpx.AsyncClient(
                        base_url="http://127.0.0.1:18080", trust_env=False, timeout=100
                    ) as client:
                        for case in frozen["cases"]:
                            rows.append(await measure(client, profile, case, root))
                        summary["profiles"][profile]["cancellation"] = await BASE[
                            "cancellation_probe"
                        ](client, profile, root)
                    summary["profiles"][profile]["provenance"] = BASE["provenance"](
                        profile
                    )
                finally:
                    await server.stop()
                    summary["profiles"][profile]["runtime"] = server.receipt()
                    if server.failure or (
                        server.exit_code is not None and server.exit_code != 0
                    ):
                        raise ValueError("structured_native_retirement_failed")
                deadline = time.monotonic() + 30
                while time.monotonic() < deadline:
                    sample = BASE["resources"]()
                    if (
                        sample["GPU_free_MiB"] >= 14 * 1024
                        and sample["available_RAM_KiB"] >= 14 * 1024**2
                    ):
                        break
                    await asyncio.sleep(0.5)
                else:
                    raise ValueError(
                        "structured_between_profile_headroom_not_recovered"
                    )
            if frozen.get("fresh_stream_compatibility_cases"):
                root = OUTPUT / "core-stream-compatibility"
                root.mkdir(mode=0o700)
                server = BASE["OwnedServer"]("core", root)
                rows = []
                summary["fresh_stream_compatibility_rows"] = rows
                try:
                    await server.start()
                    async with httpx.AsyncClient(
                        base_url="http://127.0.0.1:18080", trust_env=False, timeout=100
                    ) as client:
                        for case in frozen["fresh_stream_compatibility_cases"]:
                            rows.append(await measure(client, "core", case, root))
                finally:
                    await server.stop()
                    summary["fresh_stream_compatibility_runtime"] = server.receipt()
                    if server.failure or server.exit_code != 0:
                        raise ValueError("structured_compatibility_native_retirement")
            summary["status"] = "MEASUREMENT_COMPLETE"
    except BaseException as exc:
        summary.update(
            error_type=type(exc).__name__,
            error_code=str(exc)
            if isinstance(exc, ValueError)
            else "structured_campaign_interrupted",
        )
    finally:
        summary["after"] = BASE["local_state"]()
        summary["runtime_baseline_restored"] = summary["after"] == before
        verify_manifest(application)
        for value in summary["profiles"].values():
            rows = value["rows"]
            value.update(
                format_passed=sum(row["format_passed"] for row in rows),
                functional_passed=sum(row["functional_passed"] for row in rows),
                declared_cases=42,
                completed_cases=len(rows),
            )
        summary.update(
            assess_gate(
                summary,
                frozen["cases"],
                frozen.get("fresh_stream_compatibility_cases", []),
            )
        )
        publish(OUTPUT / "result.json", summary)
    return summary


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unmeasured-suffix", action="store_true")
    options = parser.parse_args()
    if options.unmeasured_suffix:
        OUTPUT = ROOT / "data/backups/d14-structured-suffix-20261026"
        FREEZE = ROOT / "docs/evidence/d14-structured-unmeasured-suffix-freeze.json"
    result = asyncio.run(run())
    print(
        json.dumps(
            dict(
                status=result["status"],
                format_gate=result["format_gate_passed"],
                functional_gate=result["functional_gate_passed"],
                quality_gate=result["quality_gate_passed"],
                profiles={
                    p: {
                        k: v[k]
                        for k in [
                            "completed_cases",
                            "format_passed",
                            "functional_passed",
                        ]
                    }
                    for p, v in result["profiles"].items()
                },
            ),
            sort_keys=True,
        )
    )
    raise SystemExit(0 if result["quality_gate_passed"] else 1)
